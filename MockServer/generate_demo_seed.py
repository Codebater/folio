"""Writes seed.json into the Swift demo account as a raw string literal.

    python -I MockServer/generate_demo_seed.py

Run it after editing seed.json so the in-app demo and the HTTP mock server
serve the same articles.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEED = ROOT / "MockServer" / "seed.json"
OUT = ROOT / "Packages" / "FolioFreshRSS" / "Sources" / "FolioFreshRSS" / "Demo" / "DemoSeed.swift"


def main() -> None:
    data = json.loads(SEED.read_text(encoding="utf-8"))
    data.pop("_comment", None)
    text = json.dumps(data, ensure_ascii=False, indent=1)
    if '"""#' in text:
        raise SystemExit("seed contains a raw-string terminator")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    swift = (
        "// Generated by MockServer/generate_demo_seed.py from MockServer/seed.json. Do not edit.\n\n"
        "enum DemoSeed {\n"
        '    static let json = #"""\n'
        f"{text}\n"
        '"""#\n'
        "}\n"
    )
    # newline="\n" keeps LF endings on Windows.
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(swift)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data['articles'])} articles)")


if __name__ == "__main__":
    main()
